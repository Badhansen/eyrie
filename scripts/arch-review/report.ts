import { basename } from 'node:path';
import { CHECKS, type PackageGraphs } from './checks.js';
import type { Evidence, FindingRow, ReviewDb } from './db.js';
import { evidenceState, formatEvidence } from './evidence.js';

const date = (ms: number) => new Date(ms).toISOString().replace('T', ' ').slice(0, 16) + ' UTC';

function evidenceLines(root: string, evidence: Evidence[], indent = '  '): string[] {
  return evidence.map((ev) => {
    const state = evidenceState(root, ev);
    const flag = state === 'current' ? '' : ` — **cited lines ${state} since recorded**`;
    return `${indent}- \`${formatEvidence(ev)}\`${ev.note ? ` (${ev.note})` : ''}${flag}`;
  });
}

function quote(text: string): string[] {
  return text.split('\n').map((l) => (l ? `> ${l}` : '>'));
}

/** Markdown report of the latest scan plus everything people and agents have added. */
export function renderReport(db: ReviewDb, root: string): string {
  const run = db.latestRun();
  if (!run) return 'No scans yet. Run `pnpm arch scan` first.\n';
  const stats = JSON.parse(run.stats) as { files: number; workspaces: string[]; packageGraph: PackageGraphs; graph: Record<string, number> };
  const checks = JSON.parse(run.checks) as Record<string, { ok: boolean; findings?: number; error?: string }>;
  const present = db.findings('present');
  const unknown = db.findings('unknown');
  const newThisRun = new Set(db.eventsInRun(run.id, 'observed').map((e) => e.entity_id));
  const reopened = new Set(db.eventsInRun(run.id, 'reopened').map((e) => e.entity_id));
  const resolved = db.eventsInRun(run.id, 'resolved').map((e) => db.finding(e.entity_id)).filter((f): f is FindingRow => !!f);
  const retired = db.eventsInRun(run.id, 'retired').length;
  const out: string[] = [];

  out.push(`# Architecture review: ${basename(run.root)}`, '');
  out.push('Generated by `pnpm arch report` from `.eyrie/knowledge.db`. Findings come from deterministic checks; issues and proposals were added by people and AI agents and carry their author.', '');
  out.push('| Run | Date | Commit | Snapshot | Checks | Files |', '| --- | --- | --- | --- | --- | --- |');
  out.push(`| ${run.id} | ${date(run.started_at)} | \`${run.head_commit?.slice(0, 7) ?? 'none'}\`${run.dirty ? ' + uncommitted changes' : ''} | \`${run.snapshot}\` | ${run.analyzer_version} | ${stats.files} |`, '');

  const bySeverity = (s: string) => present.filter((f) => f.severity === s).length;
  out.push('## Summary', '');
  out.push(`- **Present findings:** ${present.length} (${bySeverity('error')} error, ${bySeverity('warning')} warning, ${bySeverity('info')} info), of which ${present.filter((f) => newThisRun.has(f.fingerprint)).length} new and ${reopened.size} reopened in this run.`);
  out.push(
    `- **Resolved in this run:** ${resolved.length}.${retired ? ` **Retired** because the check logic changed (not repairs): ${retired}.` : ''} **Unknown** (check failed): ${unknown.length}.`,
  );
  out.push(`- **Triaged:** ${present.filter((f) => f.triage !== 'untriaged').length} of ${present.length}. **Baseline:** ${present.filter((f) => f.baseline).length}.`);
  out.push(`- **Issues:** ${db.issues().length}. **Proposals:** ${db.proposals().length}. **Decisions:** ${db.decisions().length}.`);
  const failed = Object.entries(checks).filter(([, c]) => !c.ok);
  if (failed.length) out.push(`- **Checks that failed:** ${failed.map(([id, c]) => `\`${id}\` (${c.error})`).join(', ')}.`);
  out.push('');

  out.push('## Package graph', '');
  out.push('Declared = `dependencies` / `devDependencies` between workspace packages. Imported = what files in `src/` import, marked "(types)" when only types are used.', '');
  out.push('| Package | Declared | Imported by source | Mismatch |', '| --- | --- | --- | --- |');
  for (const ws of stats.workspaces) {
    const declared = stats.packageGraph.declared.filter(([a]) => a === ws).map(([, b, k]) => (k === 'dev' ? `${b} (dev)` : b));
    const runtimeDeclared = new Set(stats.packageGraph.declared.filter(([a, , k]) => a === ws && k === 'dep').map(([, b]) => b));
    const actual = stats.packageGraph.actual.filter(([a]) => a === ws);
    const imported = new Set(actual.map(([, b]) => b));
    const mismatch = [
      ...actual.filter(([, b, k]) => k === 'runtime' && !runtimeDeclared.has(b)).map(([, b]) => `imports undeclared ${b}`),
      ...[...runtimeDeclared].filter((b) => !imported.has(b)).map((b) => `declares unused ${b}`),
    ];
    const shown = actual.map(([, b, k]) => (k === 'types' ? `${b} (types)` : b));
    out.push(`| \`${ws}\` | ${declared.join(', ') || '—'} | ${shown.join(', ') || '—'} | ${mismatch.join('; ') || '—'} |`);
  }
  out.push('');

  out.push('## Findings', '');
  if (!present.length) out.push('None present.', '');
  for (const severity of ['error', 'warning', 'info'] as const) {
    const group = present.filter((f) => f.severity === severity);
    if (!group.length) continue;
    out.push(`### ${severity[0]!.toUpperCase()}${severity.slice(1)} (${group.length})`, '');
    for (const check of [...new Set(group.map((f) => f.check_id))]) {
      out.push(`**\`${check}\`** — ${CHECKS[check] ?? ''}`, '');
      for (const f of group.filter((g) => g.check_id === check)) {
        const tags = [newThisRun.has(f.fingerprint) ? 'new' : reopened.has(f.fingerprint) ? 'reopened' : `since run ${f.first_run}`, f.triage, f.baseline ? 'baseline' : ''].filter(Boolean);
        out.push(`- \`${f.fingerprint.slice(0, 8)}\` ${f.title} _(${tags.join(' · ')})_`);
        if (f.triage_note) out.push(`  - Triage note: ${f.triage_note}`);
        const obs = db.latestObservation(f.fingerprint);
        if (obs) out.push(...evidenceLines(root, obs.evidence));
        const chain = obs?.detail?.importChain as string[] | undefined;
        if (chain?.length) out.push(`  - Import chain: ${chain.map((c) => `\`${c}\``).join(' → ')}`);
      }
      out.push('');
    }
  }
  if (resolved.length) {
    out.push('### Resolved in this run', '');
    for (const f of resolved) out.push(`- \`${f.fingerprint.slice(0, 8)}\` ${f.title}`);
    out.push('');
  }

  out.push('## Issues reported by people and agents', '');
  const issues = db.issues();
  if (!issues.length) out.push('None yet.', '');
  for (const i of issues) {
    out.push(`### Issue ${i.id}: ${i.title}`, '');
    out.push(`${i.severity} · ${i.status} · reported by \`${i.reporter}\` on ${date(i.created_at)}`, '');
    out.push(...quote(i.description), '', 'Evidence:', ...evidenceLines(root, JSON.parse(i.evidence) as Evidence[], ''), '');
  }

  out.push('## Proposals', '');
  const proposals = db.proposals();
  if (!proposals.length) out.push('None yet.', '');
  for (const p of proposals) {
    out.push(`### Proposal ${p.id}: ${p.title}`, '');
    out.push(`${p.kind} · for \`${p.target}\` · ${p.status} · by \`${p.author}\` on ${date(p.created_at)}`, '');
    out.push(...quote(p.body), '', 'Evidence:', ...evidenceLines(root, JSON.parse(p.evidence) as Evidence[], ''), '');
    const reviews = db.reviews(p.id);
    if (reviews.length) {
      out.push('Reviews:', '');
      for (const r of reviews) out.push(`- **${r.verdict}** by \`${r.reviewer}\`: ${r.note}`);
      out.push('');
    }
    if (p.decided_by) out.push(`Decision by \`${p.decided_by}\`: ${p.decision_note ?? ''}`, '');
  }

  const decisions = db.decisions();
  if (decisions.length) {
    out.push('## Decisions', '');
    for (const d of decisions) out.push(`- **${d.title}** — ${d.decision} (\`${d.decided_by}\`, ${date(d.created_at)})`);
    out.push('');
  }

  out.push('## Adding to this review', '');
  out.push('People and AI agents add issues, proposals and reviews through `pnpm arch`; see `scripts/arch-review/README.md`. Every claim needs `path:line` evidence. Triage and decisions are made by people.', '');
  return out.join('\n');
}
